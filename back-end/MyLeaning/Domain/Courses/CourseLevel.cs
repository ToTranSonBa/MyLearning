/// N4: Elementary
/// N3: Intermediate
/// N2: Upper-Intermediate
/// N1: Advanced
/// </summary>
public enum CourseLevel
{
    N5 = 5,  // Beginner
    N4 = 4,  // Elementary
    N3 = 3,  // Intermediate
    N2 = 2,  // Upper-Intermediate
    N1 = 1   // Advanced
}
